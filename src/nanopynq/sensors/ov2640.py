class OV2640:
    ADDR7 = 0x30
    CHIP_ID = 0x2642  # PIDH 0x0A, PIDL 0x0B in the sensor bank
    VSYNC_FRAME_HIGH = True  # after OV2640_SETTINGS_CIF, VSYNC is high during the frame (measured)

    def __init__(self, i2c: "I2C", addr7: int = ADDR7) -> None:
        self.i2c = i2c
        self.addr7 = addr7

    def _w(self, reg: int, value: int) -> None:
        self.i2c.write_reg8(self.addr7, reg, value)

    def _table(self, table: Iterable[tuple[int, int]]) -> None:
        for reg, value in table:
            self._w(reg, value)

    def chip_id(self) -> int:
        self._w(BANK_SEL, BANK_SENSOR)
        return self.i2c.read_reg8(self.addr7, 0x0A) << 8 | self.i2c.read_reg8(self.addr7, 0x0B)

    def init(self) -> None:
        """Soft reset, then the CIF initialisation table (it also enables the DVP outputs)."""
        self._w(BANK_SEL, BANK_SENSOR)
        self._w(COM7, COM7_SRST)
        time.sleep(0.01)
        self._table(OV2640_SETTINGS_CIF)

    def set_format(self, fmt: str) -> None:
        if fmt != "yuv422":
            raise ValueError(f"only 'yuv422' is supported, not {fmt!r}")
        self._table(OV2640_SETTINGS_YUV422)
        time.sleep(0.01)

    def set_size(self, width: int, height: int) -> None:
        """4:3 output sizes up to 400x296, from the CIF sensor mode (esp32-camera set_framesize/set_window).
        Call set_format() afterwards: the sensor needs the format table again after a size change."""
        if width * 3 != height * 4 or width % 4 or height % 4 or width > 400 or height > 296:
            raise ValueError(f"unsupported size {width}x{height}: 4:3, multiples of 4, up to 400x296")
        max_x, max_y, off_x, off_y = 1600 // 4, min(1200 // 4, 296), 0, 0  # CIF mode of the 4:3 window
        max_x, max_y, w, h = max_x // 4, max_y // 4, width // 4, height // 4
        win = (
            (BANK_SEL, BANK_DSP),
            (HSIZE, max_x & 0xFF),
            (VSIZE, max_y & 0xFF),
            (XOFFL, off_x & 0xFF),
            (YOFFL, off_y & 0xFF),
            (VHYX, ((max_y >> 1) & 0x80) | ((off_y >> 4) & 0x70) | ((max_x >> 5) & 0x08) | ((off_x >> 8) & 0x07)),
            (TEST, (max_x >> 2) & 0x80),
            (ZMOW, w & 0xFF),
            (ZMOH, h & 0xFF),
            (ZMHH, ((h >> 6) & 0x04) | ((w >> 8) & 0x03)),
        )
        self._table(((BANK_SEL, BANK_DSP), (R_BYPASS, R_BYPASS_DSP_BYPAS)))
        self._table(OV2640_SETTINGS_TO_CIF)
        self._table(win)
        self._table(((BANK_SEL, BANK_SENSOR), (CLKRC, 0x03)))  # clk_2x 0, clk_div 3 (CIF, not JPEG)
        self._table(((BANK_SEL, BANK_DSP), (R_DVP_SP, 0x88)))  # pclk_auto 1, pclk_div 8
        self._table(((BANK_SEL, BANK_DSP), (R_BYPASS, R_BYPASS_DSP_EN)))
        time.sleep(0.01)
